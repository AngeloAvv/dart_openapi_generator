  // -------------------------------------------------------------------------
  // Manifest poisoning protection
  // -------------------------------------------------------------------------
  group('manifest poisoning protection', () {
    late Directory tmpDir;
    late Directory cacheDir;

    setUp(() async {
      tmpDir = await Directory.systemTemp.createTemp('file_writer_test_');
      cacheDir = await Directory.systemTemp.createTemp('file_writer_cache_');
      addTearDown(() async {
        if (tmpDir.existsSync()) await tmpDir.delete(recursive: true);
        if (cacheDir.existsSync()) await cacheDir.delete(recursive: true);
      });
    });

    test(
      'manifest entry containing ".." is skipped and log message captured',
      () async {
        // Create a real file that we want to survive
        final safeFile = File('${tmpDir.path}/models/safe.dart');
        await safeFile.parent.create(recursive: true);
        await safeFile.writeAsString('class Safe {}');

        // Create a poisoned manifest with a '..' path traversal entry
        final manifestFile = File('${cacheDir.path}/manifest.json');
        await manifestFile.parent.create(recursive: true);
        await manifestFile.writeAsString(
          jsonEncode({
            'files': ['models/safe.dart', '../secret_file.dart'],
          }),
        );

        // The '..' entry should be skipped (not deleted), and log should capture the skip
        final logs = <String>[];
        final writer = FileWriter(onLog: logs.add);
        final annotation = _makeAnnotation(
          outputDir: tmpDir.path,
          cachePath: cacheDir.path,
          cleanOutput: true,
        );
        await writer.write({'models/safe.dart': _validSource}, annotation);

        // The '..' entry must be skipped — log must mention it
        final skipLogs =
            logs
                .where((m) => m.contains('skipping') || m.contains('unsafe'))
                .toList();
        expect(
          skipLogs,
          isNotEmpty,
          reason:
              'A skip log message must be emitted for the ".." manifest entry',
        );
      },
    );
  });
