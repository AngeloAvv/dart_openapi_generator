// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

ResolvedAnnotation _makeAnnotation({
  required String outputDir,
  required String cachePath,
  bool cleanOutput = false,
  bool debugLogging = false,
}) => ResolvedAnnotation(
  inputSpec: const LocalSpec('openapi.yaml'),
  outputDir: outputDir,
  clientName: 'ApiClient',
  skipIfSpecIsUnchanged: true,
  cachePath: cachePath,
  cleanOutput: cleanOutput,
  dateTimeConverter: DateTimeConverter.iso8601,
  debugLogging: debugLogging,
);

/// Simple valid Dart source that the formatter accepts.
const _validSource = '''
// GENERATED CODE - DO NOT MODIFY BY HAND
// @dart=3.0
// Generated by dart_openapi_generator

class User {}
''';

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

void main() {
  // -------------------------------------------------------------------------
  // File write to disk
  // -------------------------------------------------------------------------
  group('file write to disk', () {
    late Directory tmpDir;
    late Directory cacheDir;

    setUp(() async {
      tmpDir = await Directory.systemTemp.createTemp('file_writer_test_');
      cacheDir = await Directory.systemTemp.createTemp('file_writer_cache_');
      addTearDown(() async {
        if (tmpDir.existsSync()) await tmpDir.delete(recursive: true);
        if (cacheDir.existsSync()) await cacheDir.delete(recursive: true);
      });
    });

    test('write() creates file at outputDir/key path', () async {
      final annotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, annotation);

      final created = File('${tmpDir.path}/models/user.dart');
      expect(
        created.existsSync(),
        isTrue,
        reason: 'models/user.dart must exist on disk',
      );
    });

    test('written file content matches formatted source', () async {
      final annotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, annotation);

      final content =
          File('${tmpDir.path}/models/user.dart').readAsStringSync();
      expect(content, isNotEmpty);
      // Content must be valid Dart (formatter round-trip is idempotent)
      final formatter = DartFormatter(languageVersion: Version(3, 0, 0));
      final reformatted = formatter.format(content, uri: 'models/user.dart');
      expect(
        content,
        equals(reformatted),
        reason: 'written file must be idempotent under dart_style',
      );
    });
  });

  // -------------------------------------------------------------------------
  // Subdirectory layout (models/, services/)
  // -------------------------------------------------------------------------
  group('subdirectory layout', () {
    late Directory tmpDir;
    late Directory cacheDir;

    setUp(() async {
      tmpDir = await Directory.systemTemp.createTemp('file_writer_test_');
      cacheDir = await Directory.systemTemp.createTemp('file_writer_cache_');
      addTearDown(() async {
        if (tmpDir.existsSync()) await tmpDir.delete(recursive: true);
        if (cacheDir.existsSync()) await cacheDir.delete(recursive: true);
      });
    });

    test('key "models/user.dart" creates parent dir and file', () async {
      final annotation = _makeAnnotation(
