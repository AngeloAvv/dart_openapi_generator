  // -------------------------------------------------------------------------
  // Barrel generation
  // -------------------------------------------------------------------------
  group('barrel generation', () {
    late Directory tmpDir;
    late Directory cacheDir;

    setUp(() async {
      tmpDir = await Directory.systemTemp.createTemp('file_writer_test_');
      cacheDir = await Directory.systemTemp.createTemp('file_writer_cache_');
      addTearDown(() async {
        if (tmpDir.existsSync()) await tmpDir.delete(recursive: true);
        if (cacheDir.existsSync()) await cacheDir.delete(recursive: true);
      });
    });

    test('barrel file generated.dart is written to disk', () async {
      final annotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, annotation);

      expect(
        File('${tmpDir.path}/generated.dart').existsSync(),
        isTrue,
        reason: 'generated.dart barrel must be created',
      );
    });

    test('barrel exports are in alphabetical order', () async {
      final annotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
      );
      await const FileWriter().write({
        'services/b_api.dart': _validSource,
        'models/a.dart': _validSource,
      }, annotation);

      final barrel = File('${tmpDir.path}/generated.dart').readAsStringSync();
      final aIdx = barrel.indexOf("export 'models/a.dart'");
      final bIdx = barrel.indexOf("export 'services/b_api.dart'");
      expect(
        aIdx,
        lessThan(bIdx),
        reason: 'models/a.dart must appear before services/b_api.dart',
      );
    });

    test('barrel does NOT export generated.dart itself', () async {
      final annotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, annotation);

      final barrel = File('${tmpDir.path}/generated.dart').readAsStringSync();
      expect(
        barrel,
        isNot(contains("export 'generated.dart'")),
        reason: 'barrel must not export itself',
      );
    });

    test('barrel uses correct export syntax', () async {
      final annotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, annotation);

      final barrel = File('${tmpDir.path}/generated.dart').readAsStringSync();
      expect(barrel, contains("export 'models/user.dart'"));
    });
  });

  // -------------------------------------------------------------------------
  // Path safety guard
  // -------------------------------------------------------------------------
  group('path safety guard', () {
    late Directory cacheDir;

    setUp(() async {
      cacheDir = await Directory.systemTemp.createTemp('file_writer_cache_');
      addTearDown(() async {
        if (cacheDir.existsSync()) await cacheDir.delete(recursive: true);
      });
    });

    test('outputDir == "/" throws StateError', () async {
      final annotation = _makeAnnotation(
        outputDir: '/',
        cachePath: cacheDir.path,
      );
      await expectLater(
        () async => const FileWriter().write({
          'models/user.dart': _validSource,
        }, annotation),
        throwsA(isA<StateError>()),
      );
    });

    test('outputDir == "." throws StateError', () async {
      final annotation = _makeAnnotation(
        outputDir: '.',
        cachePath: cacheDir.path,
      );
      await expectLater(
        () async => const FileWriter().write({
          'models/user.dart': _validSource,
        }, annotation),
        throwsA(isA<StateError>()),
      );
    });

    test('outputDir == "lib" throws StateError', () async {
      final annotation = _makeAnnotation(
        outputDir: 'lib',
        cachePath: cacheDir.path,
      );
      await expectLater(
        () async => const FileWriter().write({
          'models/user.dart': _validSource,
        }, annotation),
        throwsA(isA<StateError>()),
      );
    });

    test('outputDir containing ".." throws StateError', () async {
      final annotation = _makeAnnotation(
        outputDir: 'lib/../secrets',
        cachePath: cacheDir.path,
      );
      await expectLater(
        () async => const FileWriter().write({
          'models/user.dart': _validSource,
        }, annotation),
        throwsA(isA<StateError>()),
      );
    });

    test('outputDir is a symlink throws StateError', () async {
      final realDir = await Directory.systemTemp.createTemp(
        'file_writer_real_',
      );
      addTearDown(() async {
        if (realDir.existsSync()) await realDir.delete(recursive: true);
      });
      final symlinkPath =
          '${Directory.systemTemp.path}/file_writer_symlink_${realDir.path.hashCode}';
      final link = Link(symlinkPath);
      link.createSync(realDir.path);
      addTearDown(() {
        if (link.existsSync()) link.deleteSync();
      });

      final annotation = _makeAnnotation(
        outputDir: symlinkPath,
        cachePath: cacheDir.path,
      );
      await expectLater(
        () async => const FileWriter().write({
          'models/user.dart': _validSource,
        }, annotation),
        throwsA(isA<StateError>()),
      );
    });

    test('outputDir "lib/generated" (safe path) does NOT throw', () async {
      final safeDir = await Directory.systemTemp.createTemp(
        'file_writer_safe_',
      );
      addTearDown(() async {
        if (safeDir.existsSync()) await safeDir.delete(recursive: true);
      });
      // Use an absolute safe path (not the project lib — a temp dir with /generated subdir)
      final safeOutputDir = '${safeDir.path}/generated';
      final annotation = _makeAnnotation(
        outputDir: safeOutputDir,
        cachePath: cacheDir.path,
      );
      // Must NOT throw — directly await
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, annotation);
    });
  });

  // -------------------------------------------------------------------------
  // Manifest write
  // -------------------------------------------------------------------------
  group('manifest write', () {
    late Directory tmpDir;
    late Directory cacheDir;

    setUp(() async {
      tmpDir = await Directory.systemTemp.createTemp('file_writer_test_');
      cacheDir = await Directory.systemTemp.createTemp('file_writer_cache_');
      addTearDown(() async {
        if (tmpDir.existsSync()) await tmpDir.delete(recursive: true);
        if (cacheDir.existsSync()) await cacheDir.delete(recursive: true);
      });
    });

    test('manifest.json is created at cachePath after write()', () async {
      final annotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, annotation);

      expect(
        File('${cacheDir.path}/manifest.json').existsSync(),
        isTrue,
        reason: 'manifest.json must be created in cachePath',
      );
    });

    test('manifest JSON has {"files": [...]} structure', () async {
      final annotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, annotation);

      final content = File('${cacheDir.path}/manifest.json').readAsStringSync();
      final data = jsonDecode(content) as Map<String, dynamic>;
      expect(data, containsPair('files', isA<List>()));
    });

    test(
      'manifest contains all written relative paths in sorted order',
      () async {
        final annotation = _makeAnnotation(
          outputDir: tmpDir.path,
          cachePath: cacheDir.path,
        );
        await const FileWriter().write({
          'services/z_api.dart': _validSource,
          'models/a.dart': _validSource,
        }, annotation);

        final content =
            File('${cacheDir.path}/manifest.json').readAsStringSync();
        final data = jsonDecode(content) as Map<String, dynamic>;
        final files = (data['files'] as List).cast<String>();
        // Must contain models/a.dart, services/z_api.dart, generated.dart
        expect(
          files,
          containsAll([
            'models/a.dart',
            'services/z_api.dart',
            'generated.dart',
          ]),
        );
        // Must be sorted
        final sorted = files.toList()..sort();
        expect(
          files,
          equals(sorted),
          reason: 'manifest files must be alphabetically sorted',
        );
      },
    );
  });

