  // -------------------------------------------------------------------------
  // cleanOutput manifest-driven deletion
  // -------------------------------------------------------------------------
  group('cleanOutput manifest-driven', () {
    late Directory tmpDir;
    late Directory cacheDir;

    setUp(() async {
      tmpDir = await Directory.systemTemp.createTemp('file_writer_test_');
      cacheDir = await Directory.systemTemp.createTemp('file_writer_cache_');
      addTearDown(() async {
        if (tmpDir.existsSync()) await tmpDir.delete(recursive: true);
        if (cacheDir.existsSync()) await cacheDir.delete(recursive: true);
      });
    });

    test(
      'cleanOutput: manifest-listed files are deleted before re-generation',
      () async {
        // First write: creates files and manifest
        final firstAnnotation = _makeAnnotation(
          outputDir: tmpDir.path,
          cachePath: cacheDir.path,
          cleanOutput: false,
        );
        await const FileWriter().write({
          'models/old.dart': _validSource,
        }, firstAnnotation);

        // Verify first write created the file
        expect(File('${tmpDir.path}/models/old.dart').existsSync(), isTrue);

        // Second write with cleanOutput: true — manifest from first run lists old.dart + generated.dart
        final cleanAnnotation = _makeAnnotation(
          outputDir: tmpDir.path,
          cachePath: cacheDir.path,
          cleanOutput: true,
        );
        await const FileWriter().write({
          'models/new.dart': _validSource,
        }, cleanAnnotation);

        // old.dart should be deleted (it was in the manifest)
        expect(
          File('${tmpDir.path}/models/old.dart').existsSync(),
          isFalse,
          reason: 'Manifest-listed old.dart must be deleted on cleanOutput',
        );
      },
    );

    test('cleanOutput: non-manifest files survive deletion', () async {
      // Create a non-generated file in the output dir
      final nonGenFile = File('${tmpDir.path}/user.txt');
      await nonGenFile.writeAsString('not generated');

      // First write creates manifest
      final firstAnnotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
        cleanOutput: false,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, firstAnnotation);

      // Second write with cleanOutput deletes only manifest-listed files
      final cleanAnnotation = _makeAnnotation(
        outputDir: tmpDir.path,
        cachePath: cacheDir.path,
        cleanOutput: true,
      );
      await const FileWriter().write({
        'models/user.dart': _validSource,
      }, cleanAnnotation);

      // user.txt is NOT in the manifest → must survive
      expect(
        nonGenFile.existsSync(),
        isTrue,
        reason: 'Non-manifest user.txt must survive cleanOutput',
      );
    });
  });

